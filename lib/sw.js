'use strict';
/*
  24.10.2026, stage 6 (Web Push). The service worker of the monitor page.

  build.js writes it as docs/sw.js on every build. It does three jobs and nothing
  else: it shows a push as a phone notification, opens the monitor when one is
  tapped, and keeps the app shell (the page, the manifest and the icons) for a phone
  with no connection. Encrypted data is never cached: every other request goes
  straight to the network, untouched.

  The worker is a real function so that tests can load its source and run its
  handlers with fake events. source() adds the cache name, which carries the build
  time so every build replaces the shell cache of the one before it.
*/

function worker() {
  'use strict';
  // The page itself (and any sub page ending in a slash) is network first, so a new
  // build always wins; the stored copy only answers when there is no connection.
  var PAGE_RE = /(\/|\/index\.html)$/;
  // The manifest and the icons never change under the same address (the build puts
  // a version in the query), so they are answered from the cache first.
  var STATIC_RE = /(\.webmanifest$|\/icons\/)/;

  function putCopy(req, res) {
    // The copy is taken before the page reads the body; a clone made later would fail.
    var copy = res.clone();
    caches.open(ABZ_CACHE).then(function (c) { return c.put(req, copy); })
      .catch(function (e) { console.warn('sw cache: ' + e.message); });
  }

  function networkFirst(req) {
    return fetch(req).then(function (res) {
      if (res.ok) putCopy(req, res);
      return res;
    }, function (err) {
      return caches.match(req).then(function (hit) {
        if (hit) return hit;
        throw err;
      });
    });
  }

  function cacheFirst(req) {
    return caches.match(req).then(function (hit) {
      if (hit) return hit;
      return fetch(req).then(function (res) {
        if (res.ok) putCopy(req, res);
        return res;
      });
    });
  }

  self.addEventListener('install', function () { self.skipWaiting(); });

  self.addEventListener('activate', function (event) {
    event.waitUntil(caches.keys().then(function (keys) {
      return Promise.all(keys.filter(function (k) { return k !== ABZ_CACHE; })
        .map(function (k) { return caches.delete(k); }));
    }).then(function () { return self.clients.claim(); }));
  });

  self.addEventListener('fetch', function (event) {
    var req = event.request;
    if (req.method !== 'GET') return;
    var url = new URL(req.url);
    if (url.origin !== self.location.origin) return;
    if (PAGE_RE.test(url.pathname)) event.respondWith(networkFirst(req));
    else if (STATIC_RE.test(url.pathname)) event.respondWith(cacheFirst(req));
    // Anything else, the encrypted data included, is not answered here at all.
  });

  self.addEventListener('push', function (event) {
    var data = {};
    if (event.data) {
      try { data = event.data.json(); }
      catch (e) { data = { body: event.data.text() }; }
    }
    var options = {
      body: data.body || '',
      tag: data.tag || 'monitor',
      renotify: !!data.tag,
      icon: 'icons/icon-192.png',
      dir: 'rtl',
      lang: 'he',
      data: { url: data.url || self.registration.scope }
    };
    var jobs = [self.registration.showNotification(data.title || 'המוניטור', options)];
    // The app badge is the number of approvals waiting. iOS shows it on the home icon.
    if (typeof data.badge === 'number' && self.navigator && self.navigator.setAppBadge) {
      jobs.push(self.navigator.setAppBadge(data.badge).catch(function (e) {
        console.warn('sw badge: ' + e.message);
      }));
    }
    event.waitUntil(Promise.all(jobs));
  });

  self.addEventListener('notificationclick', function (event) {
    event.notification.close();
    var target = (event.notification.data && event.notification.data.url) || self.registration.scope;
    event.waitUntil(self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then(function (list) {
      for (var i = 0; i < list.length; i++) {
        if (list[i].url.indexOf(self.registration.scope) === 0) return list[i].focus();
      }
      return self.clients.openWindow(target);
    }));
  });
}

// The file build.js writes. stamp is the build time, so each build has its own cache.
function source(stamp) {
  var cache = 'abz-shell-' + String(stamp || new Date().toISOString()).replace(/[^0-9A-Za-z]/g, '');
  return '// Generated by build.js from lib/sw.js (24.10.2026). Do not edit this file by hand.\n'
    + 'var ABZ_CACHE = ' + JSON.stringify(cache) + ';\n'
    + '(' + worker.toString() + ')();\n';
}

module.exports = { source };
