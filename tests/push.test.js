// The page template is evaluated once when build.js loads, so the key is read at
// load time: each case renders in its own child process with its own environment.
function renderInChild(key) {
  const env = Object.assign({}, process.env, { MONITOR_NO_GATE: '1' });
  if (key) env.VAPID_PUBLIC = key; else delete env.VAPID_PUBLIC;
  const script = "const {renderPage}=require(process.argv[1]);"
    + "process.stdout.write(renderPage({now:null,openCmds:[],builtAt:'2026-10-24T10:00:00.000Z',"
    + "counts:{pending:0,replied:0,today:0,leads:0},choices:[],food:[],pending:[],replied:[],contacts:[],reports:[],chat:[]}));";
  return require('child_process').execFileSync(process.execPath,
    ['-e', script, path.join(ROOT, 'build.js')], { env: env, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

test('the built page registers the worker and the subscription line, and shows the box only with a key', () => {
  const withKey = renderInChild('BPubKeyForBuild');
  const withoutKey = renderInChild('');
  assert.ok(withKey.includes('id="pushBox"'), 'box missing with a key');
  assert.ok(withKey.includes('var PUSH_KEY="BPubKeyForBuild"'));
  assert.ok(withKey.includes("navigator.serviceWorker.register('sw.js')"));
  assert.ok(withKey.includes("'מנוי התראות: '"));
  assert.ok(!withoutKey.includes('id="pushBox"'), 'box shown without a key');
  assert.ok(withoutKey.includes("navigator.serviceWorker.register('sw.js')"), 'worker not registered without a key');
});

// ---- the subscription line -------------------------------------------------------

test('a subscription line is read out of a message whatever kind line comes first', () => {
  const wp = require(path.join(ROOT, 'lib', 'webpush.js'));
  const got = wp.fromMessage('הגדרה\n' + SUB_LINE + '\n\nקוד 4821');
  assert.deepEqual(got, { sub: SUB });
  assert.equal(wp.fromMessage('שלום, מה נשמע'), null);
  assert.ok(wp.fromMessage('מנוי התראות: {שבור').error.includes('does not parse'));
  assert.ok(wp.fromMessage('מנוי התראות: {"endpoint":"http://x","keys":{"p256dh":"a","auth":"b"}}').error);
  assert.ok(wp.fromMessage('מנוי התראות: {"endpoint":"https://x"}').error);
});

test('the listener saves a checked subscription with the owner code, and refuses one without it', async () => {
  const savedCode = process.env.ABAITZIK_OWNER_CODE;
  process.env.ABAITZIK_OWNER_CODE = '4821';
  try {
    await withData(async (dir) => {
      const listen = require(path.join(ROOT, 'listen.js'));
      const wp = require(path.join(ROOT, 'lib', 'webpush.js'));
      listen.recordPushSub({ message: 'הגדרה\n' + SUB_LINE + '\n\nקוד 9999' }, { sub: SUB });
      assert.equal(wp.count(), 0, 'a wrong code must not store a phone');
      listen.recordPushSub({ message: 'הגדרה\n' + SUB_LINE + '\n\nקוד 4821' }, { sub: SUB });
      assert.equal(wp.count(), 1);
      listen.recordPushSub({ message: 'קוד 4821' }, { sub: SUB });
      assert.equal(wp.count(), 1, 'the same phone is kept once');
      assert.ok(fs.existsSync(path.join(dir, 'push', 'subs.json')));
    });
  } finally {
    if (savedCode === undefined) delete process.env.ABAITZIK_OWNER_CODE; else process.env.ABAITZIK_OWNER_CODE = savedCode;
  }
});

test('the subscription is caught before the chat: the listener never forwards it', () => {
  const src = fs.readFileSync(path.join(ROOT, 'listen.js'), 'utf8');
  const start = src.indexOf('async function handleOne(m)');
  const hook = src.indexOf('wp.fromMessage(m.message)', start);
  assert.ok(start > 0 && hook > start, 'hook missing inside handleOne');
  assert.ok(hook < src.indexOf("say('הודעה: '", start), 'the hook must run before the message is chatted');
  const chat = src.indexOf('recordIncoming(m)', start);
  assert.ok(chat === -1 || hook < chat, 'the hook must run before the chat record');
});

