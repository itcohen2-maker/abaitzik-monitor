// A fetch that answers each address as the test says, and records the addresses.
function fakeFetch(answers) {
  const calls = [];
  const real = global.fetch;
  global.fetch = async (url) => {
    calls.push(String(url));
    const host = String(url).split('/')[2];
    const status = answers[host] || 200;
    return { ok: status < 300, status, text: async () => '{}' };
  };
  return { calls, restore: () => { global.fetch = real; } };
}

test('a notification goes to the phones first and draws from the shared daily count', async () => {
  await withData(async () => {
    const wp = require(path.join(ROOT, 'lib', 'webpush.js'));
    const ch = require(path.join(ROOT, 'lib', 'notify-channels.js'));
    const sent = [];
    wp.sendAll = async (t, b) => { sent.push([t, b]); return { sent: 1, failed: 0 }; };
    const f = fakeFetch({});
    try {
      const r = await ch.notify('מחכה לך', 'אישור');
      assert.equal(r.ok, true);
      assert.equal(r.channel, 'push');
      assert.deepEqual(sent, [['מחכה לך', 'אישור']]);
      assert.deepEqual(f.calls, [], 'no ntfy or mail when the phones got it');
      assert.equal(ch.budget().ntfy.used, 1, 'push spends from the ntfy budget');
      assert.equal(ch.budget().push, undefined, 'push is not listed on its own');
    } finally { f.restore(); }
  }, { keys: true, subs: [SUB] });
});

test('when the phones fail, ntfy takes it; when ntfy fails too, the mailbox does; all fail, it is queued', async () => {
  await withData(async () => {
    const wp = require(path.join(ROOT, 'lib', 'webpush.js'));
    const ch = require(path.join(ROOT, 'lib', 'notify-channels.js'));
    wp.sendAll = async () => { const e = new Error('push: 0 of 1 phones reached'); e.statusCode = 500; throw e; };

    let f = fakeFetch({});
    try {
      const r = await ch.notify('t', 'b');
      assert.equal(r.channel, 'ntfy');
      assert.ok(r.tried[0].startsWith('push:'), 'the push failure is recorded: ' + r.tried[0]);
      assert.deepEqual(f.calls, ['https://ntfy.sh/test-out-topic']);
    } finally { f.restore(); }

    f = fakeFetch({ 'ntfy.sh': 500 });
    try {
      const r = await ch.notify('t', 'b');
      assert.equal(r.channel, 'mail');
      assert.equal(r.tried.length, 2);
    } finally { f.restore(); }

    f = fakeFetch({ 'ntfy.sh': 500, 'formsubmit.co': 500 });
    try {
      const r = await ch.notify('t', 'b');
      assert.equal(r.ok, false);
      assert.equal(r.queued, true);
      assert.equal(r.tried.length, 3);
      assert.equal(ch.queueLength(), 1, 'nothing is dropped');
    } finally { f.restore(); }
  }, { keys: true, subs: [SUB] });
});

test('a push refused with 429 blocks only the push channel, not ntfy', async () => {
  await withData(async () => {
    const wp = require(path.join(ROOT, 'lib', 'webpush.js'));
    const ch = require(path.join(ROOT, 'lib', 'notify-channels.js'));
    wp.sendAll = async () => { const e = new Error('too many'); e.statusCode = 429; throw e; };
    const f = fakeFetch({});
    try {
      const r = await ch.notify('t', 'b');
      assert.equal(r.channel, 'ntfy');
      const again = await ch.notify('t', 'b');
      assert.equal(again.channel, 'ntfy');
      assert.deepEqual(again.tried, ['push:no budget'], 'push is skipped while blocked: ' + JSON.stringify(again.tried));
    } finally { f.restore(); }
  }, { keys: true, subs: [SUB] });
});

test('without keys or without a subscribed phone the push channel is not offered at all', async () => {
  await withData(async () => {
    const wp = require(path.join(ROOT, 'lib', 'webpush.js'));
    const ch = require(path.join(ROOT, 'lib', 'notify-channels.js'));
    let called = 0;
    wp.sendAll = async () => { called++; return { sent: 1, failed: 0 }; };
    const f = fakeFetch({});
    try {
      const r = await ch.notify('t', 'b');
      assert.equal(r.channel, 'ntfy');
      assert.equal(called, 0, 'no keys: the phones are not tried');
      assert.deepEqual(r.tried, [], 'no keys: nothing is said about push');
    } finally { f.restore(); }
  }, { keys: false, subs: [SUB] });

  await withData(async () => {
    const wp = require(path.join(ROOT, 'lib', 'webpush.js'));
    const ch = require(path.join(ROOT, 'lib', 'notify-channels.js'));
    let called = 0;
    wp.sendAll = async () => { called++; return { sent: 1, failed: 0 }; };
    const f = fakeFetch({});
    try {
      const r = await ch.notify('t', 'b');
      assert.equal(r.channel, 'ntfy');
      assert.equal(called, 0, 'keys but no phone: nothing to send to');
    } finally { f.restore(); }
  }, { keys: true });
});

test('a gone subscription is dropped from the list, the other phones still get it', async () => {
  const other = { endpoint: 'https://push.example.test/send/other', keys: { p256dh: 'p', auth: 'a' } };
  await withData(async (dir) => {
    const wp = require(path.join(ROOT, 'lib', 'webpush.js'));
    wp.dropSub(SUB.endpoint);
    assert.deepEqual(wp.readSubs().map((s) => s.endpoint), [other.endpoint]);
    assert.ok(fs.existsSync(path.join(dir, 'push', 'subs.json')));
  }, { keys: true, subs: [SUB, other] });
});

