/*
  24.10.2026, stage 6 (Web Push). What is pinned here:
  - the service worker source is written by build.js and its handlers do what they say,
    with network data never answered by the worker,
  - the page carries the push box (only with a key) and always registers the worker,
  - a subscription line from the page is parsed, stored on the server, and never chatted,
  - the channel order is push, ntfy, mail, and push is skipped when it is not set up.
  No test sends anything: every push and every fetch is a fake.
*/
const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const os = require('os');
const vm = require('vm');

process.env.MONITOR_NO_GATE = '1';
const ROOT = path.join(__dirname, '..');
const FILE = path.join(os.tmpdir(), 'abaitzik-push-' + process.pid + '.json');
process.env.ABAITZIK_INSTANCE_FILE = FILE;

function fresh() {
  for (const k of Object.keys(require.cache)) {
    if (k.startsWith(ROOT) && !k.includes('node_modules')) delete require.cache[k];
  }
}

const SUB = {
  endpoint: 'https://push.example.test/send/abc123',
  keys: { p256dh: 'BPretendKeyForTests', auth: 'AuthForTests' },
};
const SUB_LINE = 'מנוי התראות: ' + JSON.stringify(SUB);

// A private data folder with fake keys, the instance pointed at it, then restored.
async function withData(fn, opts) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'abaitzik-push-data-'));
  fs.mkdirSync(path.join(dir, 'status'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'keys.json'), JSON.stringify({
    ntfyIn: 'test-in-topic', ntfyLive: 'test-live-topic', ntfyOut: 'test-out-topic', mail: 'itcohen2@gmail.com',
  }));
  if (opts && opts.subs) {
    fs.mkdirSync(path.join(dir, 'push'), { recursive: true });
    fs.writeFileSync(path.join(dir, 'push', 'subs.json'), JSON.stringify(opts.subs));
  }
  const saved = fs.existsSync(FILE) ? fs.readFileSync(FILE) : null;
  const savedEnv = { pub: process.env.VAPID_PUBLIC, priv: process.env.VAPID_PRIVATE };
  try {
    fs.writeFileSync(FILE, JSON.stringify({ dataDir: dir }));
    if (opts && opts.keys) { process.env.VAPID_PUBLIC = 'PUB-test'; process.env.VAPID_PRIVATE = 'PRIV-test'; }
    else { delete process.env.VAPID_PUBLIC; delete process.env.VAPID_PRIVATE; }
    fresh();
    return await fn(dir);
  } finally {
    if (saved !== null) fs.writeFileSync(FILE, saved); else if (fs.existsSync(FILE)) fs.unlinkSync(FILE);
    if (savedEnv.pub === undefined) delete process.env.VAPID_PUBLIC; else process.env.VAPID_PUBLIC = savedEnv.pub;
    if (savedEnv.priv === undefined) delete process.env.VAPID_PRIVATE; else process.env.VAPID_PRIVATE = savedEnv.priv;
    fresh();
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

